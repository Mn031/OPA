"""
model.py - GRU-based NextWordModel for Federated Text Language Modeling.

Architecture:
  nn.Embedding(vocab_size, 32, padding_idx=0)
  -> nn.GRU(32, 64, batch_first=True)
  -> nn.Linear(64, vocab_size)

Includes get_weights() and set_weights() for NumPy/Flower parameter extraction and loading.
"""

from typing import List, Optional, Tuple
import numpy as np
import torch
import torch.nn as nn


class NextWordModel(nn.Module):
    """
    Lightweight GRU NextWordModel for word-level language modeling.
    Dynamically adapts to any vocab_size generated by WordTokenizer.
    """
    def __init__(self, vocab_size: int, embed_dim: int = 32, hidden_dim: int = 64):
        super().__init__()
        self.vocab_size = vocab_size
        self.embed_dim = embed_dim
        self.hidden_dim = hidden_dim

        self.embedding = nn.Embedding(vocab_size, embed_dim, padding_idx=0)
        self.gru = nn.GRU(embed_dim, hidden_dim, batch_first=True)
        self.fc = nn.Linear(hidden_dim, vocab_size)

    def forward(
        self,
        x: torch.Tensor,
        hidden: Optional[torch.Tensor] = None,
    ) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        Forward pass for next-word prediction.
        
        Args:
            x: Input tensor of token IDs with shape (batch_size, seq_len).
            hidden: Optional initial hidden state for GRU.
            
        Returns:
            logits: Output tensor of shape (batch_size, seq_len, vocab_size).
            hidden: Updated GRU hidden state.
        """
        embeds = self.embedding(x)
        out, hidden = self.gru(embeds, hidden)
        logits = self.fc(out)
        return logits, hidden

    def get_weights(self) -> List[np.ndarray]:
        """Extracts model parameters as a list of NumPy arrays for Flower."""
        return [param.detach().cpu().numpy() for param in self.parameters()]

    def set_weights(self, weights: List[np.ndarray]) -> None:
        """Loads model parameters from a list of NumPy arrays."""
        for param, w in zip(self.parameters(), weights):
            param.data = torch.tensor(w, dtype=param.dtype, device=param.device)
